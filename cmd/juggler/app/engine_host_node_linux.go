package app

import (
	"os/exec"
	"syscall"
)

// setChildDeathSignal asks the kernel to send SIGTERM to the node child if this
// process dies, so a crashed or force-killed server never orphans a live node
// engine. Linux-only (Pdeathsig); node mode is a Linux-first, headless path.
func setChildDeathSignal(cmd *exec.Cmd) {
	if cmd.SysProcAttr == nil {
		cmd.SysProcAttr = &syscall.SysProcAttr{}
	}
	cmd.SysProcAttr.Pdeathsig = syscall.SIGTERM
}
