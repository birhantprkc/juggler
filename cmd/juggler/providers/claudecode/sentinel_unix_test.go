package claudecode

import "os/exec"

// sentinelCommand returns a process that blocks on stdin so it stays alive
// until killed. /bin/cat reads stdin forever when nothing is written.
func sentinelCommand() *exec.Cmd { return exec.Command("/bin/cat") }
